"""Application-owned persistence interfaces; adapters own storage details."""

from typing import Callable, Protocol, TypeVar

from .domain import Case, ServiceRequest

T = TypeVar("T")


class Transaction(Protocol):
    def get_request(self, identifier: str) -> ServiceRequest | None: ...
    def get_case(self, identifier: str) -> Case | None: ...
    def insert_request(self, item: ServiceRequest) -> None: ...
    def update_request(self, item: ServiceRequest, expected_version: int) -> None: ...
    def insert_case(self, item: Case) -> None: ...
    def update_case(self, item: Case, expected_version: int) -> None: ...
    def find_result(self, actor: str, request_id: str) -> tuple[str, dict] | None: ...
    def save_result(self, actor: str, request_id: str, digest: str, result: dict) -> None: ...
    def append_event(self, event: dict) -> None: ...
    def admit_replay(self, actor: str, session: str, opcode: int, nonce: str, digest: str) -> None: ...
    def get_revision(self, identifier: str) -> dict | None: ...
    def insert_revision(self, revision: dict) -> None: ...
    def revision_history(self, case_id: str, after: int, limit: int) -> list[dict]: ...
    def get_handoff(self, event_id: str) -> dict | None: ...
    def handoff_for_revision(self, revision_id: str) -> dict | None: ...
    def insert_handoff(self, handoff: dict) -> None: ...
    def update_handoff(self, handoff: dict, expected_version: int) -> None: ...
    def pending_handoffs(self, after: str, limit: int) -> list[dict]: ...
    def handoff_counts(self) -> dict: ...
    def record_delivery_attempt(self, event_id: str, attempt: int, result: dict) -> None: ...


